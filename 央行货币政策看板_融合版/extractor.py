def clean_title(raw_title):
    """
    标题清洗（2026-07-21 重写）：
    网页抓取的标题常粘连正文开头（"7月3日央行官网公布…"），
    按"第8字后出现的正文起始标志"取最早者截断；阈值保护避免误伤
    《1—6月…》《前7个月…》等真实含时间表述的标题
    """
    t = re.sub(r'[\u200b\u200d\ufeff]', '', (raw_title or '').strip())
    if '...' in t[:80]:
        idx = t.index('...')
        if idx > 5:
            t = t[:idx]
    patterns = ['\\d{1,2}月\\d{1,2}日', '\\d{4}年\\d{1,2}月', '\\d{1,2}月份', '\\d{1,2}月末', '\\d{4}年末', '去年\\d{1,2}月', '近日', '日前', '近期', '本报讯', '本报', '在20\\d{2}年', '了解到', '官网消息', '——网友', '根据央行', '截至', '在当前', '今年的', '央行最新发布', '据金融时报', '全国两会期间', '中共中央关于', '以下简称', '金融是国民经济', '随着我国', '为保持银行体系', '根据中国人民银行', '中国人民银行授权', '金融时报记者从', '《金融时报》记者从', '根据《?金融时报》?记者从', '央行官网', '当前[，,]']
    cut = len(t)
    for pat in patterns:
        m = re.search(pat, t)
        if m and 7 <= m.start() < cut:
            cut = m.start()
    if cut < len(t):
        t = t[:cut]
    t = re.sub(r'[\s（\(，,。、：:；;！!—\-——]+$', '', t).strip()
    t = re.sub(r'((中国人民银行|人民银行|央行|根据|据|获悉|了解到|当前))+$', '', t).strip()
    t = re.sub(r'(《金融时报》记者|金融时报记者)$', '', t).strip()
    t = re.sub(r'[在与和及对为将及]$', '', t).strip()
    if len(t) > 50:
        for punct in [' ', '——', '：', '！', '？']:
            idx = t.find(punct, 20, 55)
            if idx > 0:
                t = t[:idx].strip()
                break
        else:
            t = t[:50]
    return t if len(t) >= 5 else (raw_title or '').strip()


def display_title(article):
    """
    看板展示用标题：优先文章页自身的权威标题（title_page，即页面上黑色大标题），
    抓取失败时回退到模式截断清洗 clean_title。
    """
    pt = (article.get('title_page') or '').strip()
    if len(pt) >= 2:
        return pt
    return clean_title(article.get('title', ''))


def is_skip_article(content, title, tag):
    """
    判断文章是否为叙事/案例/法律类，应该全部留空
    """
    # 1. 法律修订类
    if any(k in title for k in ['人民银行法', '修订草案', '审议']):
        return True
    # 2. 标题含"一线观察"/"落地一线"/"调研"等，通常为企业调研
    if any(k in title for k in ['一线观察', '落地一线', '调研', '走访']):
        return True
    # 3. 标题含"春雨"/"润"等文学化标题，通常是叙事报道
    if any(k in title for k in ['春雨', '润鹏城', '润']):
        return True
    # 3.5 分行文章：标题以"中国人民银行xx分行"或"人民银行xx分行"开头
    if re.search(r'^(中国人民银行|人民银行).{1,8}分行(?!长)', title):
        return True
    # 3.6 纯图表文章："一图看懂""一图读懂"
    if re.search(r'^一图(看懂|读懂)', title):
        return True

    # 4. 正文特征判断：大量企业案例/叙事内容
    # 如果正文中出现大量企业故事特征词，且没有央行官员表态
    narrative_signals = [
        '企业负责人', '企业有关业务负责人', '客户经理',
        '该企业', '这家企业', '一家企业', '某企业',
        '车间', '流水线', '生产', '订单', '采购',
        '微众银行', '农商银行', '深圳',
    ]
    narrative_count = sum(1 for k in narrative_signals if k in content)
    # 有官员/专家表态的标志
    has_official_quote = bool(re.search(
        r'(邹澜|潘功胜|谢光启|闫先东|宣昌能|刘国强|朱鹤新).{0,10}(表示|指出|认为|强调|介绍|称)',
        content
    ))
    if narrative_count >= 5 and not has_official_quote:
        return True

    # 5. 纯融资成本/信贷数据解读文章（如"信贷结构优化 融资成本保持低位"）
    # 特征：大量利率数据 + 企业案例，但没有央行政策表态
    if tag == '利率政策':
        data_signals = ['加权平均利率', '贷款利率', '融资成本', '贷款明白纸',
                        'LPR', '基点', '利率优惠', '过桥费']
        data_count = sum(1 for k in data_signals if k in content)
        case_signals = ['企业负责人', '客户经理', '记者在调研', '记者了解到',
                        '专精特新', '小巨人', '无还本续贷']
        case_count = sum(1 for k in case_signals if k in content)
        # 含业内专家/市场人士观点的不跳过（2026-07-22 修复）：
        # 月度"贷款利率低位"系列报道常顺带提及"无还本续贷/客户经理"，
        # 但正文有"业内专家表示"等观点句，属于有内容文章，不应误杀
        has_expert_quote = bool(re.search(
            r'(业内专家|市场人士|市场分析人士|分析人士|专家)'
            r'.{0,8}(表示|认为|分析|指出|称|预计)', content))
        if data_count >= 3 and case_count >= 2 \
                and not has_official_quote and not has_expert_quote:
            return True

    return False


def extract_core_view(content, title, tag, title_page=None):
    result = {
        '经济形势判断': [],
        '工作重点': [],
        '货币政策取向': [],
        '资金态度': [],
        '债券市场态度': [],
        '国债买卖': []
    }
    max_per_dim = 3

    # 先判断是否为应跳过的文章类型
    if is_skip_article(content, title, tag):
        for key in result:
            result[key] = ['/']
        return result

    # --- 清理正文 ---
    text = content
    text = re.sub(r'^.*?分享[：，,、]?\s*', '', text, count=1)
    text = re.sub(r'^本报讯\s*记者.{2,4}报道\s*', '', text)
    for p in [
        r'责任编辑.*$', r'版权声明.*$', r'专题.*$',
        r'•\s*天津举办.*$', r'•\s*甘肃甘南.*$',
        r'•\s*浙江青田.*$', r'•\s*中国人民银行武威市分行.*$',
        r'•\s*中国人民银行佳木斯.*$', r'•\s*中国人民银行大连市分行.*$',
        r'回应·共同关切.*$', r'活力中国调研行.*$',
        r'伟大征程.*$', r'树立和践行正确政绩观.*$',
        r'党建引领.*$', r'产业一线调查.*$',
        r'货币政策落地跟踪可视化.*$',
    ]:
        text = re.sub(p, '', text, flags=re.DOTALL)

    sentences = re.split(r'(?<=[。！？；])\s*', text)

    is_pure_data = bool(re.search(
        r'^(\d+月末|[\d\uff10-\uff19]+月[末底])[^。]{0,30}?(存量|余额|增量|统计)',
        title
    ))
    is_lpr_flash = bool(re.match(r'^(刚刚|最新)?[，,]?\s*LPR\s*发布', title, re.I))
    leader_stmt = is_leader_statement(title, title_page)
    # 国债买卖重大一次性公告（暂停/恢复/决定/启动/首次）：
    # 公告事实句本身即为政策信号，豁免下方的公告口吻过滤（2026-07-22 用户规则11）
    is_major_gb_notice = tag == '国债买卖' and \
        bool(re.search(r'暂停|恢复|决定|启动|首次', title))

    # --- 逐句提取 ---
    for s in sentences:
        s = s.strip()
        if not s or len(s) < 15:
            continue
        if re.match(r'^(来源|作者|发布时间|分享|责编|版权)[:：]', s):
            continue
        if re.match(r'^[\d\s\.,，%万亿亿元个只]+[。！？]?$', s):
            continue
        # 标题查重必须用页面权威标题：CSV合并文章的原始标题粘连了大段正文，
        # 整句正文都被粘进标题，会误杀全部摘句（2026-07-22 修复，影响暂停国债等短公告）
        _chk_title = title_page or title
        if s in _chk_title or _chk_title in s:
            continue

        # 跳过纯叙事/背景句
        if re.match(r'^(深圳|宝安|一家|某|这家|该企业|企业|记者|据记者|2025年末|2026年|今年|近期|当下|过去|一直以来)', s):
            if not re.search(r'(表示|指出|认为|预计|强调|称|分析|判断)', s[:50]):
                continue

        # 领导表态文章：纯活动叙述句（会见/出席/开幕式等且无表态动词）直接跳过
        if leader_stmt and re.search(
                r'(会见|会面|签署|合影|访问|考察|致辞|调研|慰问|出席|开幕式|闭幕式)', s):
            if not re.search(r'(表示|强调|指出|宣布|介绍|谈到|透露|部署|要求|'
                             r'会议指出|会议强调|会议认为|说[：，,])', s):
                continue

        # 跳过纯数据描述句（但保留含经济判断关键词的句子）
        if re.match(r'^(截至|数据显示|6月末|上半年|一季度|从.*?看)', s) and '%' in s:
            if not re.search(r'(表示|指出|认为|预计|强调)', s):
                # 如果含经济形势关键词（GDP/CPI/PPI/物价/回升/向好等），不跳过
                if not re.search(r'(gdp|cpi|ppi|物价|回升向好|稳中有进|良好开局|向好|平稳运行|经济运行)', s.lower()):
                    continue

        # 跳过企业案例/融资细节描述
        if re.search(r'(贷款明白纸|过桥费|无还本续贷|专精特新.*?贷|知识产权质押|客户经理.*?发现)', s):
            continue
        if re.match(r'^(一位|某|西部|当地|该企业)', s) and re.search(r'(企业|公司|负责人)', s):
            continue

        # === 2026-07-22 用户审核规则（五维度摘句第一轮反馈）===
        # 规则6：问句不放（记者提问/设问句），只保留央行/专家的回答与陈述
        if s.rstrip().endswith('？'):
            continue
        # 规则4：美国统计与联储内容不纳入
        if re.search(r'(美国|美联储|联邦基金|美债|硅谷银行|华尔街)', s):
            continue
        # 规则7：结构性货币政策工具不摘（只关心总量型）
        if re.search(r'(结构性货币政策|支农支小|创业担保|碳减排|普惠养老|'
                     r'交通物流.*?再贷款|设备更新.*?再贷款|'
                     r'科技创新(和技术改造)?再贷款|保交楼|供应链金融)', s):
            continue
        # 金融结构/信贷结构叙事（非经济形势判断）
        if re.search(r'(多层次、多元化金融体系|新旧动能转换|轻资产|'
                     r'全周期融资需求|信贷结构.{0,8}优化|'
                     r'融资结构.{0,6}(改善|优化)|直接融资.{0,6}(加快|扩容))', s):
            continue
        # 裸GDP数据句（无判断内容）
        if re.match(r'^(初步核算[，,]?)?(一季度|上半年|前三季度|全年|20\d{2}年|今年)?[，,]?'
                    r'(国内生产总值（GDP）|国内生产总值|GDP)同比(增长|下降)[\d.]+[%％][，,]?。?$',
                    s.strip()):
            continue
        # 规则10：剥离"期待，/市场期待，"残句句头；剥离后无主语残句（通过/把开头）跳过
        s = re.sub(r'^(市场|大家|市场普遍)?期待[，,]\s*', '', s)
        if re.match(r'^(通过|把)[^为]', s):
            continue
        if len(s) < 15:
            continue

        # 规则8：纯回顾/总结句不摘（政策效果回顾与工作总结属事实陈述，非取向表态）
        if re.search(r'(效果|成效|效应)(逐步|持续|不断)(显现|释放|显效)|累积效应|'
                     r'是货币政策适度宽松的重要体现|'
                     r'创造了适宜的货币金融环境|创造了良好的货币金融环境', s):
            continue
        if re.match(r'^((对此|同时|此外|另外|特别是|尤其是)[，,]?)?'
                    r'(\d{1,2}月(上|中|下)?旬以来|今年以来|去年(以来)?|'
                    r'一年来|一年多来|近年来|此前|上半年|202\d年|'
                    r'[^。]{0,8}会议以来|从(前期|近期|近日).{0,14}(政策|操作|表态|数据|会议)(来看|可以看出))'
                    r'[，,]?', s):
            if re.search(r'(适度宽松|支持性|逆周期|一揽子|增量政策|存量政策|'
                         r'货币金融环境|形成合力|组合拳|出台了一系列|围绕中心|'
                         r'服务大局|框架转型|有效稳定市场预期)', s):
                if not re.search(r'(将会|将继续|要继续|下一步|下阶段|展望|预计|未来)', s):
                    continue

        # === 提取策略 ===
        quotes_from_this = []

        # 策略QA: 答记者问的回答句（"答：……"格式，用户规则6：问句已在前置过滤跳过）
        if not quotes_from_this:
            mqa = re.match(r'^答[：:]\s*(.{12,400}?)\s*[。！？]?$', s)
            if mqa:
                quotes_from_this.append((mqa.group(1), '答记者问', 'qa'))

        # 策略1: 带引号的直接引语
        # 注意："分析"不能单独作为说话动词，否则会把"分析师王青"截断成"师王青"
        # 解决：用负向断言 analysis(?!师)，确保"分析"后面不是"师"
        # 同时把"分析说"作为完整搭配，避免"分析"先匹配导致"说"残留在引语中
        m = re.match(
            r'^(.{2,25}?(?:表示|指出|认为|分析称|分析认为|分析表示|分析道|分析说|'
            r'分析(?![师说])|'
            r'说|介绍|强调|称|判断|回应|预计|'
            r'感慨道|看来|补充道|谈到|告诉记者|对.{2,15}表示|表示道))'
            r'[：，,、\s]*["""\u201c\u2018]*'
            r'(.+?)'
            r'["""\u201d\u2019]*\s*[。！？]?$',
            s
        )
        if m:
            speaker = m.group(1).strip()
            quote_text = m.group(2).strip().strip('"""\u201c\u201d\u2018\u2019')
            # 清理引语开头的残留标点（如"说，当前"中的逗号）
            quote_text = re.sub(r'^[，,、：:。\s]+', '', quote_text)
            # 排除企业人士的引语（非政策观点）
            if not re.search(r'(企业负责人|企业.*?负责人|公司负责人|业务负责人|黎先生|实控人)', speaker):
                if len(quote_text) >= 15:
                    quotes_from_this.append((quote_text, speaker, 'quote'))

        # 策略2: 引号在前
        if not quotes_from_this:
            m = re.match(
                r'^["""\u201c\u2018]*(.+?)["""\u201d\u2019]+\s*[,，]?\s*'
                r'(.{2,20}?(?:表示|指出|认为|分析称|分析认为|分析表示|分析道|'
                r'说|介绍|强调|称|判断|'
                r'回应|预计|告诉记者|表示道))\s*[。！？]?$',
                s
            )
            if m:
                quote_text = m.group(1).strip()
                speaker = m.group(2).strip()
                if not re.search(r'(企业负责人|企业.*?负责人|公司负责人|业务负责人|黎先生|实控人)', speaker):
                    if len(quote_text) >= 15:
                        quotes_from_this.append((quote_text, speaker, 'quote'))

        # 策略3: 业内人士/专家表示
        if not quotes_from_this:
            m = re.match(
                r'^((?:业内人士|业内专家|专家|市场分析人士|市场人士|'
                r'分析人士|业内人士认为|业内人士预计|业内人士分析|'
                r'业内专家认为|业内专家预计|'
                r'招联首席经济学家.{2,8}|东方金诚首席宏观分析师.{2,8}|'
                r'中信证券首席经济学家.{2,8}|中国民生银行首席经济学家.{2,8}))'
                r'(表示|认为|分析称|分析认为|分析表示|预计|指出|称|表示道)?[：，,、]?\s*'
                r'(.+?)\s*[。！？]?$',
                s
            )
            if m:
                quote_text = m.group(3).strip()
                quote_text = re.sub(r'^[，,、：:。\s]+', '', quote_text)
                if len(quote_text) >= 15:
                    quotes_from_this.append((quote_text, m.group(1), 'expert'))

        # 策略4: 总结性陈述
        if not quotes_from_this:
            m = re.match(
                r'^(综合来看|总体来看|总体上说|总体上看|由此|总的来看)'
                r'[，,：]?\s*(.+?)\s*[。！？]?$',
                s
            )
            if m:
                quote_text = m.group(2).strip()
                if len(quote_text) >= 15:
                    quotes_from_this.append((quote_text, '总结', 'conclusion'))

        # 策略5: 核心政策叙述句
        if not quotes_from_this and not is_pure_data and not is_lpr_flash:
            if re.search(
                r'(明确释放|这标志着|这意味着|明确将|'
                r'将继续实施|继续实施好|将继续保持|将增强|将根据|'
                r'下阶段|下半年|下一步)',
                s[:80]
            ):
                if len(s) >= 20 and len(s) <= 400:
                    quotes_from_this.append((s, '叙述', 'core_text'))

        # 策略6: 纯经济描述句（非引语、非政策叙述，但含经济现状关键词）
        # 解决：GDP/CPI/物价等经济数据句不含"XX表示"，不会被策略1-5命中
        if not quotes_from_this and not is_pure_data and not is_lpr_flash:
            if len(s) >= 20 and len(s) <= 400:
                # 先用 classify_dimension 判断是否为经济形势判断
                test_dims = classify_dimension(s, tag)
                if '经济形势判断' in test_dims:
                    quotes_from_this.append((s, '经济描述', 'eco_text'))

        # 策略0（末位兜底）: 央行领导署名表态文章的转述句（2026-07-22 新增）
        # 行长演讲/记者会文章的实质内容常为转述句：或带超长日期场合前缀
        # （"3月6日，在十四届……记者会上，中国人民银行行长潘功胜表示，"）
        # 超出策略1说话人25字上限；或直接省略主语（"目标体系方面，将把…"）。
        # 对这类文章，剥离前缀后直接按政策维度归类
        if not quotes_from_this and leader_stmt:
            if 15 <= len(s) <= 400 and not re.search(
                    r'(会见|会面|签署|合影|访问|考察|致辞|调研|慰问)', s):
                sc = re.sub(
                    r'^(\d{1,2}月\d{1,2}日[，,]?)?[^。]{0,60}?'
                    r'(?:' + '|'.join(LEADER_NAMES) + r')'
                    r'[^。]{0,22}?(?:表示|强调|指出|称|介绍|谈到|透露|说|宣布)'
                    r'[：，,、]?\s*', '', s)
                if len(sc) < 8:
                    sc = s
                if classify_dimension(sc, tag):
                    quotes_from_this.append((sc, '央行领导表态', 'leader'))

        # === 维度分类 ===
        for quote_text, speaker, stype in quotes_from_this:
            # 统一清理开头/结尾的引号（中文左右引号、英文引号、单引号）
            quote_text = quote_text.strip('"""\u201c\u201d\u2018\u2019\u201b\'')

            # 纯操作公告句过滤（2026-07-22 新增）：
            # "中国人民银行发布公告表示，为保持银行体系流动性充裕，X月开展了
            # XX亿元XX操作"——公告口吻转述的纯事实操作内容不构成观点
            # （MLF规则：读不到观点的纯事实描述不进看板）。
            # 仅过滤公告口吻（speaker含公告/官网/通知）；专家/官员亲口所说、
            # 或含信号/解读/首次/正式启动等观点性内容的句子不受影响
            if re.search(
                    r'(开展|进行|完成|启动|招标|申报|到期|净买入|净卖出|'
                    r'中标|展期|费率|面值为)[^。]{0,60}?'
                    r'(操作|亿元|债券|票据|互换)', quote_text):
                ann_voice = re.search(r'(公告|官网|通知)', speaker)
                has_view = re.search(
                    r'(信号|意味着|表明|解读|认为|专家|人士|预计|分析|'
                    r'观点|判断|正式启动|首次)', quote_text)
                if ann_voice and not has_view and not is_major_gb_notice:
                    continue
            quote_text = re.sub(r'^[，,、：:。\s]+', '', quote_text)
            if not quote_text or len(quote_text) < 10:
                continue

            # 裸GDP数据句（引语级兜底：句子级过滤拦的是整句，
            # "XX表示，一季度GDP同比增长5%"剥掉说话人后仍会漏出，2026-07-22）
            if re.match(r'^(初步核算[，,]?)?(一季度|上半年|前三季度|全年|20\d{2}年|今年)?[，,]?'
                        r'(国内生产总值（GDP）|国内生产总值|GDP)同比(增长|下降)[\d.]+[%％][，,]?。?$',
                        quote_text):
                continue

            # v5新增：修复断句不干净的问题
            # 如果引语以"了""的是""着"等助词开头，说明前面的动词被截断了
            # 需要从原始句子中找回完整内容
            if re.match(r'^(了|着|的是|的是，)', quote_text):
                # 从原始句子s中找回完整句子
                # 找到quote_text在s中的位置，向前找到完整句子的开头
                pos = s.find(quote_text[:10])
                if pos > 0:
                    # 向前找主语/动词开头
                    prefix = s[:pos]
                    # 找最后一个说话动词
                    vm = re.search(r'((?:回应|分析|介绍|指出|表示|强调|称|谈到|讨论|说明|提出|回顾|部署)\s*[了将]?)\s*$', prefix)
                    if vm:
                        quote_text = vm.group(1) + quote_text
                    else:
                        # 向前找句号或主语
                        # 找最近的句号/分号/冒号后的内容
                        sm = re.search(r'[。！？；：]\s*(.{2,15})$', prefix)
                        if sm:
                            quote_text = sm.group(1) + quote_text

            # v6新增：修复引语以"时报》记者采访时表示，"等报刊残留开头的问题
            # 根因：说话人"温彬在接受《金融时报》记者采访时表示"被截断成"时报》记者采访时表示"
            # 修复：去掉这些前缀残留，只保留正文内容
            quote_text = re.sub(r'^[》」』\u300b\u3011].*?(记者采访时|记者).{0,5}(表示|指出|认为|称|分析|谈到|强调)[，,：:]\s*', '', quote_text)
            quote_text = re.sub(r'^(时报|日报|周刊|证券报|金融报|经济报|早报|晚报|都市报|新华日报|证券时报)[》」』].*?(记者采访时|记者).{0,5}(表示|指出|认为|称|分析|谈到|强调)[，,：:]\s*', '', quote_text)
            # 也处理"采访时表示，"开头
            quote_text = re.sub(r'^采访时?(表示|指出|认为|称)[，,：:]\s*', '', quote_text)
            # 处理"记者采访时表示，"开头
            quote_text = re.sub(r'^记者采访时?(表示|指出|认为|称)[，,：:]\s*', '', quote_text)
            quote_text = quote_text.strip()

            if not quote_text or len(quote_text) < 10:
                continue

            # 先尝试拆分：如果一句话同时包含经济现状和政策应对
            # 把经济现状部分单独提取出来
            eco_part, policy_part = split_eco_from_policy(quote_text)

            # 如果拆出了纯经济现状部分，需经过 classify_dimension 确认是经济形势判断
            # （残句守卫：以虚词/助动词结尾的不完整片段直接丢弃，2026-07-22 用户规则2）
            if eco_part and not _is_fragment(eco_part):
                eco_part = eco_part.strip('"""\u201c\u201d\u2018\u2019\u201b\'')
                eco_part = re.sub(r'^[，,、：:。\s]+', '', eco_part)
                if eco_part and not _is_fragment(eco_part):
                    eco_dims = classify_dimension(eco_part, tag)
                    if '经济形势判断' in eco_dims and \
                       eco_part not in result['经济形势判断'] and \
                       len(result['经济形势判断']) < max_per_dim:
                        result['经济形势判断'].append(eco_part)

            # 对政策部分（或未拆分的完整句子）做正常维度分类
            text_to_classify = policy_part if eco_part else quote_text
            if text_to_classify:
                text_to_classify = text_to_classify.strip('"""\u201c\u201d\u2018\u2019\u201b\'')
                text_to_classify = re.sub(r'^[，,、：:。\s]+', '', text_to_classify)
            if text_to_classify and not _is_fragment(text_to_classify):
                dims = classify_dimension(text_to_classify, tag)
                for dim in dims:
                    # 只有当 eco_part 存在时，才跳过经济形势判断（因为已单独处理）
                    # 如果 eco_part 为 None，说明没有拆分，需要正常填入经济形势判断
                    if dim == '经济形势判断' and eco_part:
                        continue  # 已单独处理，跳过
                    if len(result[dim]) < max_per_dim:
                        if text_to_classify not in result[dim]:
                            result[dim].append(text_to_classify)

    # 国债买卖重大公告保底（2026-07-22 用户规则11）：
    # 暂停/恢复/决定/启动/首次类公告的事实句无说话动词，六策略抓不到，
    # 但公告本身即为政策信号，直接入国债买卖维度
    if is_major_gb_notice and not result['国债买卖']:
        for s2 in re.split(r'(?<=[。！？；])\s*', text):
            s2 = s2.strip()
            if 20 <= len(s2) <= 250 and re.search(r'人民银行|央行', s2) \
                    and re.search(r'国债|债券', s2):
                result['国债买卖'].append(s2)
                break

    for key in result:
        if not result[key]:
            result[key] = ['/']
    return result


def split_eco_from_policy(text):
    """
    将一句话拆分为"经济现状描述"和"政策应对"两部分。
    例如："我国经济运行总体平稳、向新向优...但要继续实施适度宽松的货币政策..."
    → eco_part = "我国经济运行总体平稳、向新向优..."
    → policy_part = "要继续实施适度宽松的货币政策..."

    如果句子是纯经济描述（不含政策应对），返回 (None, text)
    如果句子是纯政策（不含经济描述），返回 (None, text)
    如果句子混合了两部分，返回 (eco_part, policy_part)
    """
    # 政策应对的标志词——出现这些词意味着从经济描述转入了政策表态
    policy_markers = [
        '要继续实施', '将继续实施', '继续实施好',
        '要继续', '要加大', '将加大',
        '把握好货币政策', '加大逆周期',
        '下阶段', '下半年', '下一步',
        '继续实施适度宽松',
        '要更好发挥', '更好发挥',
        '加强货币财政',
        # v3新增：政策建议/未来政策方向
        '未来货币政策需要', '需要更多采用',
        # v4新增：邀功型句式拆分点
        '货币政策接连出台', '货币政策接连出招', '货币政策接连推出',
        '货币政策频频发力',
        # 2026-07-22 用户规则3：混合句进一步拆分
        # "……不确定性因素依然较多，货币政策有必要保持合理空间……"
        '货币政策有必要', '货币政策要', '货币政策将', '货币政策会',
        '人民银行将', '央行将', '财政政策要', '宏观政策要',
    ]

    # 经济现状的标志词
    eco_markers = [
        '经济运行', '发展态势', '韧性活力',
        '供强需弱', '结构分化', '外部冲击',
        '总体平稳', '向新向优', '稳中向好',
        'k型复苏', '宏观经济呈现',
        '经济起步有力', '经济持续稳中向好',
        'cpi涨幅', 'ppi回升', '输入性因素',
        'gdp增速',
        # v3新增
        '经济循环', '堵点', '结构性矛盾',
        # v4新增：常见经济描述短语
        '外部环境不确定性', '有效需求', '经济结构深度调整',
        '需求不足', '物价', '回升向好',
        '经济面临', '风险挑战', '经济回升',
    ]

    has_eco = any(k in text for k in eco_markers)
    # 找最早出现的政策标志词的位置
    earliest_policy_pos = None
    for marker in policy_markers:
        pos = text.find(marker)
        if pos >= 0:
            if earliest_policy_pos is None or pos < earliest_policy_pos:
                earliest_policy_pos = pos

    if earliest_policy_pos is not None and earliest_policy_pos > 5:
        # 检查拆分点之前的部分是否真的含有经济描述
        eco_text_before_policy = text[:earliest_policy_pos]
        has_eco_before = any(k in eco_text_before_policy for k in eco_markers)
        if has_eco_before:
            # 句子同时包含经济现状和政策应对，拆分
            eco_part = eco_text_before_policy.rstrip('，,；;。！？ ')
            policy_part = text[earliest_policy_pos:].strip()
            if len(eco_part) >= 8 and len(policy_part) >= 8:
                return (eco_part, policy_part)

    # 2026-07-22 用户规则5/9：LPR归因句式
    # "LPR……按兵不动，根本原因是受……推动，（宏观形势段），（下半年）货币政策得以保持较强定力"
    # → eco=归因段+后续宏观段；policy=结论段（观察期/定力/必要性），无结论段则全归经济形势
    m = re.search(r'(根本原因是|主要原因是|原因主要是|原因是|背后是|背后的是)'
                  r'(受[^。]{6,180}?(?:推动|带动|支撑))', text)
    if not m:
        m = re.search(r'(根本原因是|主要原因是|原因主要是|原因是|背后是|背后的是)'
                      r'([^。]{8,180}?(?:起步有力|较快发展|加速发展|高增长|'
                      r'明显改善|止跌回升|全面改善|韧性|加快增长))', text)
    if m and re.search(r'(LPR|政策利率|按兵不动)', text):
        tail = text[m.end():].strip('，,；; ')
        pol = re.search(
            r'((?:(?:上|下)半年|今年|明年|[一二三四]季度)?[，,]?'
            r'(?:但|但是|然而|而)?\s*(?:当前)?'
            r'(?:LPR下降的必要性[，,、]?迫切性不高|降息的必要性[^。]{0,15}|'
            r'必要性[，,、]?迫切性不高|货币政策将?处于观察期|处于观察期|'
            r'(?:宏观政策|货币政策)?(?:得以)?保持了?较强定力|'
            r'政策利率和LPR报价保持稳定|LPR报价保持稳定))', tail)
        if pol:
            pre = tail[:pol.start()].strip('，, ')
            pre = re.sub(r'^这意味着[，,]?', '', pre)
            eco_part = (m.group(2) + ('，' + pre if pre else '')).strip('，, ')
            eco_part = eco_part.replace('这意味着尽管', '尽管')
            policy_part = tail[pol.start():].strip('，, ')
            policy_part = re.sub(r'^(但|但是|然而|而)[，,]?', '', policy_part)
            if len(eco_part) >= 8 and len(policy_part) >= 6 and \
                    not _is_fragment(eco_part):
                return (eco_part, policy_part)
        else:
            eco_part = m.group(2) + ('，' + tail if tail else '')
            eco_part = eco_part.strip('，, ')
            if len(eco_part) >= 8 and not _is_fragment(eco_part):
                return (eco_part, '')

    return (None, text)


# 残句守卫：拆分/提取出的片段若以虚词/助动词结尾，属于断句不干净，判无效。
# 注意："间/内/中/以/于"单独结尾多为完整句（8%-9%之间、合理区间内、足以、用于），
# 只有"短期内/期内"等明确残句形态才算 dangling（2026-07-22 修正）
_DANGLING_END = re.compile(
    r'(时|之际|期间|情况下|前提下|背景下|下|的|和|与|及|在|对|为|将|会|要|'
    r'把|被|让|使|向|从|由|而|并|或|且|以及|短期|长期|目前|当前|短期内|期内)$')


def _is_fragment(part):
    """判断片段是否为不完整句子（残句）"""
    p = (part or '').strip()
    if len(p) < 12:
        return True
    return bool(_DANGLING_END.search(p))


