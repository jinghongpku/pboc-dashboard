# ============================================================
# 央行领导署名表态识别（2026-07-22 新增）
# 行长/副行长署名表态类文章（如"潘功胜：进一步健全货币政策框架"），
# 标题与正文均承载政策立场，应保留；会见/出席/调研等活动报道除外
# ============================================================

LEADER_NAMES = ('潘功胜', '易纲', '郭树清', '邹澜', '宣昌能', '陆磊',
                '朱鹤新', '陶玲', '张青松', '刘国强', '陈雨露')
LEADER_RE = re.compile(r'^(%s)[：:，,、]?' % '|'.join(LEADER_NAMES))
LEADER_ACTIVITY_RE = re.compile(
    r'(会见|会面|出席|访问|签署|致辞|调研|慰问|看望|合影|参加)')


def is_leader_statement(title, title_page=None):
    """
    标题以央行行长/副行长姓名开头且非活动报道 → 署名表态类文章。
    姓名判定用原始标题（姓名总在开头）；活动词判定必须用页面权威标题
    （原始标题粘连正文，正文里的"出席/会见"会造成误杀）
    """
    t = title or ''
    if not LEADER_RE.match(t):
        return False
    return not LEADER_ACTIVITY_RE.search(title_page or t)


