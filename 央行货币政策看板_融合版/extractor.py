def classify_article(title, title_page=None):
    """根据标题关键词对文章进行分类，返回(tag, should_include)"""
    t = title.lower()
    # 央行领导署名表态优先通道（2026-07-22 新增）：
    # 标题以行长/副行长姓名开头且涉政策实质（非会见/出席活动），
    # 如"潘功胜宣布将在上海实施八项政策举措""潘功胜主持召开金融支持实体经济座谈会"。
    # 须先于排除词检查——此类标题常粘连正文，正文里的"征信/金融服务"等
    # 排除词会造成误杀（如八项举措正文含"个人征信机构"）
    if is_leader_statement(title, title_page):
        if re.search(r'货币政策|流动性|利率|政策|举措|座谈会|再贷款|'
                     r'国债|债券|金融稳定|风险|调控|框架|信贷|融资|'
                     r'降准|汇率|工具|对外开放', t):
            return '货币政策/宏观调控', True
    # 排除非货币政策相关
    exclude_patterns = [
        r'消费者权益|反诈|防骗|养老金融|数字人民币试点|征信|存款保险|'
        r'跨境人民币结算|金融教育|普惠金融宣传|反洗钱|绿色金融|外汇管理|'
        r'金融创新|供应链金融|自贸区|自贸港|金融服务|金融科技|金融安全|'
        r'金融犯罪|非法集资|民间借贷|P2P|虚拟货币|区块链|加密货币|'
        r'金融乱象|金融腐败|金融控股|金融租赁|消费金融|'
        r'汽车金融|信托公司|保险公司|证券公司|基金公司|期货公司|'
        r'金融期货|金融衍生品'
    ]
    for pattern in exclude_patterns:
        if re.search(pattern, t):
            return None, False
    # 流动性投放
    if any(k in t for k in ['逆回购操作', 'mlf操作', '中期借贷便利',
                              '买断式逆回购', '降准', '流动性', '削峰填谷',
                              '流动性投放', '央行开展', '央行进行']):
        if any(k in t for k in ['逆回购', 'mlf', '中期借贷', '买断式',
                                  '降准', '流动性', '隔夜逆回购']):
            return '流动性投放', True
    # 利率政策
    if any(k in t for k in ['lpr', '贷款利率', '存款利率', '利率走廊',
                              '利率调控', '融资成本', '融资利率', '利率政策',
                              '降息', '利率市场化', '首付款比例']):
        return '利率政策', True
    # 国债买卖
    # 2026-07 补充"债市"：与 classify_dimension 的 bond_keywords 保持一致，
    # 修复《债市热点问答》《警惕债市"踩踏"风险》等央行债市态度文章的漏判
    # 2026-07-21 再补充"买入/卖出国债"：修复《中国人民银行决定阶段性暂停
    # 在公开市场买入国债》等公告的漏判
    if any(k in t for k in ['国债买卖', '央行买卖国债', '国债收益率',
                              '长端利率', '债券收益率', '债市',
                              '买入国债', '国债买入', '卖出国债', '国债卖出']):
        return '国债买卖', True
    # 金融统计数据（2026-07-21 补充"金融总量"：修复《金融总量增速有所回升》漏判）
    if any(k in t for k in ['社会融资', '社融', '信贷', 'm2', '货币供应',
                              '人民币贷款', '金融统计数据', '金融数据',
                              '社会融资规模', '金融统计', '托管余额',
                              '人民币存款', '金融总量']):
        return '金融统计数据', True
    # 货币政策例会
    if any(k in t for k in ['货币政策委员会', '货币政策例会', '例会释放']):
        return '货币政策例会', True
    # 货币政策/宏观调控
    # 2026-07 补充"央行宣布"：修复《央行宣布多项利好政策首席详解》
    # （陆家嘴论坛新工具/新机制发布）的漏判
    # 2026-07-21 定稿补充：底线思维、答记者问、定调/信号/发声/表态
    if any(k in t for k in ['宏观调控', '货币政策', '宏观审慎', '双支柱',
                              '货币政策框架', '金融调控', '货币创造',
                              '金融改革', '金融稳定', '中央银行法',
                              '金融稳定法', '利率传导', '政策协同',
                              '央行宣布', '底线思维', '记者问']):
        return '货币政策/宏观调控', True
    # 定调/信号/发声/表态类：拦截纯外部部门主题（财政部/商务部等非央行主体），
    # 其余（央行、金融监管总局、宏观数据解读等）保留
    if any(k in t for k in ['定调', '信号', '发声', '表态']):
        external = re.search(
            r'财政部|商务部|住建部|发改委|外汇局|支付清算|协会|'
            r'人大代表|政协|工信部|公安|最高检|最高法|'
            r'农业农村部|交通运输部|文旅|教育部|卫健', t)
        if not external:
            return '货币政策/宏观调控', True
        return None, False
    # 宏观点评（2026-07-21 新增标签）：物价/内卷/价格战等宏观看点评论，
    # 拦截行业监管类标题（新规/指南/协会/车圈等）
    if any(k in t for k in ['物价', '价格总水平', 'cpi', 'ppi',
                              '通胀', '通缩', '内卷', '价格战']):
        industry = re.search(r'新规|指南|协会|工信部|市监|医保|车圈|行业', t)
        if not industry:
            return '宏观点评', True
        return None, False
    return None, False


