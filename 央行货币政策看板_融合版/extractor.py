    # === 维度分配 ===
    # 关键修正：如果同时命中货币政策取向和工作重点
    # "适度宽松" + "逆周期调节"同时出现时
    # → 货币政策取向（因为核心是表态"适度宽松"）
    # → 工作重点（因为提到了具体操作方向"逆周期调节"）
    # 两者都可以入，但如果只是框架改革/工具完善类（如"持续提升精准性"）
    # → 只入工作重点，不入货币政策取向

